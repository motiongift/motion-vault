// the lines that end a failed or cancelled step: each says "Nothing was changed." in its language (test/passkey-copy.mjs)
export const PK_NOTHING_CHANGED: readonly PkKey[] = ['cancelled', 'errNotAllowed', 'errInvalidState', 'errSecurity', 'errOther', 'noPrfCreate', 'noPrfSecond',
  'noPrfDiffer', 'noAnswer', 'elsewhere', 'wrong', 'needsFile', 'lockedFirst', 'unsupportedOrigin', 'unsupportedApp', 'fpMismatch'];

// one line in a language: {name}-style placeholders filled from params, a plural picked by params.n
export function pkT(key: PkKey, lang: unknown, params: PkParams = {}): string {
  const l = rkLangOf(lang);
  let v: string | PkPlural | undefined = PK_COPY[l]?.[key] ?? PK_COPY.en[key];
  if (v && typeof v === 'object') {
    let form: string = 'other';
    try { form = new Intl.PluralRules(l).select(Number(params.n) || 0); } catch { /* no Intl: `other` */ }
    v = (v as Record<string, string | undefined>)[form] ?? v.other;
  }
  return String(v ?? key).replace(/\{(\w+)\}/g, (m, k: string) => (Object.prototype.hasOwnProperty.call(params, k) ? String(params[k]) : m));
}

const esc = (v: unknown) => String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c] as string);

// "Step 2 of 4" and a thin bar of `of` segments, `n` of them lit — the head of a step dialog (webEngine askChoice, AskOpts.step).
// The bar is decoration (aria-hidden): the label says it in words. Classes only: the frame's CSP ignores inline styles.
export function pkStepHtml(step: { n: number; of: number }, lang: unknown): string {
  const of = Math.max(1, Math.min(9, Math.floor(Number(step?.of) || 1)));
  const n = Math.max(1, Math.min(of, Math.floor(Number(step?.n) || 1)));
  const segs = Array.from({ length: of }, (_, i) => `<i${i < n ? ' class="on"' : ''}></i>`).join('');
  return `<p class="dk-step"><span class="dk-step-t">${esc(pkT('stepOf', lang, { n, of }))}</span><span class="dk-bar" aria-hidden="true">${segs}</span></p>`;
}

// the remove dialog's warning, from the same counts recoveryPaths (src/passkeyBackup.ts) words in English
export function pkWarnKey(r: { passkeys: number; synced: number; code: boolean }): PkKey | null {
  const ways = r.passkeys + (r.code ? 1 : 0);
  return ways <= 1 ? 'warnOneWay' : r.passkeys && !r.synced && !r.code ? 'warnNoSync' : null;
}

